#include <iostream>
using namespace std;

int main()
{
    int arr[] = {8, 3, 6, 2, 7, 1};
    int n = 6;
    
    //冒泡排序
    for(int i = 0; i < n - 1; i++)
    {
        for(int j = 0; j < n - 1 - i; j++)
        {
            if(arr[j] > arr[j + 1])
            {
                //交换两个数
                int temp = arr[j];
                arr[j] = arr[j + 1];
                arr[j + 1] = temp;
            }
        }
    }
    
    //输出结果
    cout << "从小到大排序结果:";
    for(int i = 0; i < n; i++)
    {
        cout << arr[i] << " ";
    }
    return 0;
}

/*
1. 你的程序是如何完成排序的？
答：程序使用两层for循环实现排序。外层循环控制一共要进行多少轮比较；内层循环在每一轮中，从数组开头向后依次比较相邻两个元素。
如果前面数字大于后面的数字，就交换这两个数的值。每一轮结束后，当前未排序区间最大的元素就会“冒泡”移动到靠后的位置，多轮执行之后，整个数组就变成从小到大有序。

2. 冒泡排序的基本思路是什么？
答：重复遍历待排序数组，依次比对相邻一对元素，如果二者顺序颠倒就交换它们。一趟遍历可以将当前未排序部分最大的元素移动到数组末尾，这个过程很像水里气泡向上浮起，因此命名为冒泡排序。

3. 如果要改成从大到小排序，需要修改哪里？
答：只修改if判断里面的大于号。
原来：if(arr[j] > arr[j + 1])
改为：if(arr[j] < arr[j + 1])
修改之后，相邻元素前面更小的时候就交换，最终数组降序（从大到小）。
*/
